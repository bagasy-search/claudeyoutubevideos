// build_cmecalor.mjs — exact phrase-level assembly for Claudio Mendoza Constructor.
// Timing comes only from the real avatar audio transcription in _v3/cmecalor_moments_ms.json.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

const SLUG = 'cmecalor';
const COMP = 'Cmecalor';
const FPS = 30;
const momentsPath = fs.existsSync(`_v3/${SLUG}_moments_ms_v2.json`)
  ? `_v3/${SLUG}_moments_ms_v2.json`
  : `_v3/${SLUG}_moments_ms.json`;
const manifestPath = fs.existsSync(`_v3/${SLUG}_asset_manifest_v2.json`)
  ? `_v3/${SLUG}_asset_manifest_v2.json`
  : `_v3/${SLUG}_asset_manifest.json`;
const audioFile = `${SLUG}_fish.wav`;
const avatarFile = `avatar_${SLUG}.mp4`;

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const probeDuration = (file) => Number(execFileSync('ffprobe', [
  '-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nk=1:nw=1', file,
], {encoding: 'utf8'}).trim());
const frame = (ms) => Math.max(0, Math.round(ms / 1000 * FPS));

for (const file of [momentsPath, manifestPath, `public/${audioFile}`, `public/${avatarFile}`]) {
  if (!fs.existsSync(file)) throw new Error(`Missing required input: ${file}`);
}

const timed = readJson(momentsPath);
const manifest = readJson(manifestPath);
const audioSeconds = probeDuration(`public/${audioFile}`);
const avatarSeconds = probeDuration(`public/${avatarFile}`);
const totalFrames = Math.ceil(audioSeconds * FPS);
const avatarFrames = Math.ceil(avatarSeconds * FPS);

const cues = [];
const addCue = ({key, start, dur, type, src, clipDuration = null, kicker = null, side = null, anchor, nouns, sourceMoment}) => {
  if (!(dur > 0) || !src) return;
  cues.push({key, start, dur, type, src, clipDuration, kicker, side, anchor, nouns, sourceMoment});
};

for (const moment of timed.moments) {
  const start = frame(moment.start_ms);
  const end = Math.max(start + 12, frame(moment.end_ms));
  const dur = Math.max(12, end - start);

  if (moment.manual_assets?.length) {
    const each = Math.max(12, Math.floor(dur / moment.manual_assets.length));
    let cursor = start;
    for (let index = 0; index < moment.manual_assets.length; index += 1) {
      const remaining = start + dur - cursor;
      const pieceDur = index === moment.manual_assets.length - 1 ? remaining : Math.min(each, remaining);
      addCue({
        key: `${moment.id}_${index + 1}`,
        start: cursor,
        dur: pieceDur,
        type: 'float',
        src: moment.manual_assets[index],
        kicker: index === 0 ? 'Escanea con tu celular' : 'Capítulo: microgeneradores',
        side: index % 2 === 0 ? 'right' : 'left',
        anchor: moment.anchor,
        nouns: moment.nouns,
        sourceMoment: moment.id,
      });
      cursor += pieceDur;
    }
    continue;
  }

  // The approved still is the safe full-span floor. If an Agnes clip exists, it covers only
  // its real duration at native speed; the identical still remains underneath for the tail.
  addCue({
    key: `${moment.id}_still`,
    start,
    dur,
    type: 'still',
    src: moment.still,
    anchor: moment.anchor,
    nouns: moment.nouns,
    sourceMoment: moment.id,
  });

  if (moment.clip) {
    const clipSeconds = probeDuration(path.join('public', moment.clip));
    const clipFrames = Math.max(12, Math.floor(Math.max(0.4, clipSeconds - 0.12) * FPS));
    addCue({
      key: `${moment.id}_clip`,
      start,
      dur: Math.min(dur, clipFrames),
      type: 'clip',
      src: moment.clip,
      clipDuration: Number(clipSeconds.toFixed(3)),
      anchor: moment.anchor,
      nouns: moment.nouns,
      sourceMoment: moment.id,
    });
  }
}

// Stable z-order: earlier broad phrases are the floor; later/narrower clauses cover them only
// while their own words are spoken. Within one moment the animated clip sits above its still.
const typeOrder = {still: 0, clip: 1, float: 2};
cues.sort((a, b) => a.start - b.start || b.dur - a.dur || typeOrder[a.type] - typeOrder[b.type] || a.key.localeCompare(b.key));

const cueFile = `src/${SLUG}/cues_${SLUG}.gen.ts`;
const mainFile = `src/${SLUG}/Main_${SLUG}.tsx`;
const entryFile = `src/index_${SLUG}.tsx`;
fs.mkdirSync(`src/${SLUG}`, {recursive: true});
fs.mkdirSync('beatsheet', {recursive: true});

fs.writeFileSync(cueFile, `// GENERATED by build_cmecalor.mjs.\n` +
  `export type CmecalorCue = {key:string;start:number;dur:number;type:"still"|"clip"|"float";src:string;clipDuration:number|null;kicker:string|null;side:"left"|"right"|null;anchor:string;nouns:string[];sourceMoment:string};\n` +
  `export const CUES_CMECALOR = ${JSON.stringify(cues, null, 2)} as const satisfies readonly CmecalorCue[];\n`);

fs.writeFileSync(mainFile, `// GENERATED by build_cmecalor.mjs. No captions by design.\n` +
`import React from "react";\n` +
`import {Audio, Video} from "@remotion/media";\n` +
`import {AbsoluteFill, OffthreadVideo, Sequence, staticFile, useCurrentFrame} from "remotion";\n` +
`import {RawShot} from "../VideoEdit/scenes/RawShot";\n` +
`import {FloatingInsert} from "../VideoEdit/scenes/FloatingInsert";\n` +
`import {CUES_CMECALOR} from "./cues_cmecalor.gen";\n\n` +
`export const TOTAL_FRAMES_CMECALOR = ${totalFrames};\n` +
`export const AVATAR_FRAMES_CMECALOR = ${avatarFrames};\n\n` +
`const AvatarFloor: React.FC = () => {\n` +
`  const frame = useCurrentFrame();\n` +
`  const scale = 1.018 + Math.sin(frame / 1100) * 0.008;\n` +
`  return <AbsoluteFill style={{backgroundColor:"#10100d",overflow:"hidden"}}>\n` +
`    <Video src={staticFile("${avatarFile}")} muted style={{width:"100%",height:"100%",objectFit:"cover",transform: "scale(" + scale.toFixed(4) + ")"}} />\n` +
`  </AbsoluteFill>;\n` +
`};\n\n` +
`export const MainCmecalor: React.FC = () => (\n` +
`  <AbsoluteFill style={{backgroundColor:"#10100d"}}>\n` +
`    <AvatarFloor />\n` +
`    {CUES_CMECALOR.map((cue) => (\n` +
`      <Sequence key={cue.key} from={cue.start} durationInFrames={cue.dur} premountFor={30}>\n` +
`        {cue.type === "float" ? (\n` +
`          <FloatingInsert durationInFrames={cue.dur} src={cue.src} side={cue.side ?? "right"} kicker={cue.kicker ?? undefined} hue="amber" />\n` +
`        ) : cue.type === "clip" ? (\n` +
`          <OffthreadVideo src={staticFile(cue.src)} muted playbackRate={1} style={{width:"100%",height:"100%",objectFit:"cover"}} />\n` +
`        ) : (\n` +
`          <RawShot durationInFrames={cue.dur} src={cue.src} darken={0} blur={0} kbBoost={0.55} />\n` +
`        )}\n` +
`      </Sequence>\n` +
`    ))}\n` +
`    <Audio src={staticFile("${audioFile}")} />\n` +
`  </AbsoluteFill>\n` +
`);\n`);

fs.writeFileSync(entryFile, `import "./index.css";\n` +
`import React from "react";\n` +
`import {Composition, registerRoot} from "remotion";\n` +
`import {MainCmecalor, TOTAL_FRAMES_CMECALOR} from "./cmecalor/Main_cmecalor";\n` +
`const RootCmecalor: React.FC = () => <Composition id="${COMP}" component={MainCmecalor} durationInFrames={TOTAL_FRAMES_CMECALOR} fps={${FPS}} width={1920} height={1080} />;\n` +
`registerRoot(RootCmecalor);\n`);

const beats = cues.map((cue) => ({
  id: cue.key,
  start: Number((cue.start / FPS).toFixed(3)),
  dur: Number((cue.dur / FPS).toFixed(3)),
  kind: cue.type === 'float' ? 'float' : 'raw',
  src: cue.src,
  hue: 'amber',
  darken: 0,
  noSplit: true,
  anchor: cue.anchor,
  nouns: cue.nouns,
  sourceMoment: cue.sourceMoment,
}));
fs.writeFileSync(`beatsheet/${SLUG}.json`, `${JSON.stringify({
  video: SLUG,
  avatar: avatarFile,
  audio: audioFile,
  tutorial: true,
  clipsfirst: false,
  fps: FPS,
  totalFrames,
  timingSource: timed.timing_source,
  beats,
}, null, 2)}\n`);

const assetEntries = new Set([avatarFile, audioFile]);
for (const asset of manifest.assets) {
  if (asset.file) assetEntries.add(asset.file.replace(/^public\//, ''));
  if (asset.blur) assetEntries.add(asset.blur.replace(/^public\//, ''));
}
for (const cue of cues) assetEntries.add(cue.src);
fs.writeFileSync(`_${SLUG}_assets.txt`, `${[...assetEntries].sort().join('\n')}\n`);

console.log(JSON.stringify({
  slug: SLUG,
  composition: COMP,
  totalFrames,
  durationSeconds: Number((totalFrames / FPS).toFixed(3)),
  avatarFrames,
  cues: cues.length,
  clips: cues.filter((cue) => cue.type === 'clip').length,
  stills: cues.filter((cue) => cue.type === 'still').length,
  floats: cues.filter((cue) => cue.type === 'float').length,
  assets: assetEntries.size,
  outputs: [cueFile, mainFile, entryFile, `beatsheet/${SLUG}.json`, `_${SLUG}_assets.txt`],
}, null, 2));
